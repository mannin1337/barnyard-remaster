class MODAPI AModStrings
{
public:
	// The text of the current language, English if it has none
	static const TWCHAR* Get( MODSTRING a_eString );

	// The English text and the id of a text
	static const TWCHAR* GetEnglish( MODSTRING a_eString );
	static const TCHAR*  GetId( MODSTRING a_eString );

	// printf into a_wszOut with a text as the format ( Format( wszLine, 160, Get( MODSTRING_... ), ... ) ): the %s of a
	// text take wide strings. The result is cut to a_iSize - 1 characters without the assertion of
	// TStringManager::String16Format (a translation can be longer than the English text). Returns its length
	static TINT Format( TWCHAR* a_wszOut, TINT a_iSize, const TWCHAR* a_wszFormat, ... );

	// Loads the texts of the language of a locale table ("Data/Locale/hun.trb" -> "Data/Locale/hun_mod.json"), English
	// where there's no file or no text. The texts of the previous language stay readable until the next load
	static void Load( const TCHAR* a_szLocaleFileName );

	// Frees the texts (the game is closing)
	static void Unload();

	// The number of texts of the current language that aren't English
	static TINT GetNumTranslated();
};
